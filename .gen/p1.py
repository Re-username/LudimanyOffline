cldr = json.load(open(GEN + '/ru_annotations.json', encoding='utf-8'))
ANN = cldr['annotations']['annotations']

def _ann(em):
    return ANN.get(em) or ANN.get(em.replace('\ufe0f', ''))

def _first(d):
    t = d.get('tts') or d.get('default') or ['херня']
    b = t[0] if isinstance(t, list) else t
    return b.split(':')[0].split(',')[0].strip().lower() or 'херня'

def base_name(em):
    d = _ann(em)
    if d:
        return _first(d)
    if '\u200d' in em:
        parts = em.split('\u200d')
        if any(p.replace('\ufe0f', '') in ('👧', '👦', '🧒', '👶') for p in parts):
            return 'семья'
        for p in parts:
            dd = _ann(p)
            if dd:
                return _first(dd)
    d = _ann(em[0])
    return _first(d) if d else 'херня'

