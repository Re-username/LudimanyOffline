MASC_A = {'мужчина','дедушка','папа','дядя','юноша','слуга','вождь','космонавт'}
FEM_HINTS = ('женщин','девушк','девочк','бабушк','пожилая','королев','принцесс')

def gender_of(b):
    toks = b.split()
    w = toks[0] if toks else b
    if any(t in ('часов', 'часа') for t in toks):
        return 'pl'
    if w in PL_EXC:
        return 'pl'
    for h in FEM_HINTS:
        if h in w:
            return 'f'
    if w.endswith('мя'):
        return 'n'
    if w.endswith(('ы', 'и')) and len(w) > 2:
        return 'pl'
    if w.endswith(('о', 'е')):
        return 'n'
    if w.endswith(('а', 'я')):
        return 'm' if w in MASC_A else 'f'
    if w.endswith('ь'):
        return 'm' if w in MASC_SOFT else 'f'
    return 'm'

