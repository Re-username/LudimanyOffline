HIST_P = 0.015

def gen_name(i, em):
    rng = random.Random(5000 + i)
    if em in OVERRIDES:
        return OVERRIDES[em], 'ovr'
    b = base_name(em)
    g = gender_of(b)
    roll = rng.random()
    if roll < 0.15:
        p = rng.choice(POSS)
        return f"{p[GI[g]]} {b}", 'poss'
    elif roll < 0.47:
        return rng.choice(SPECIAL)(b), 'spec'
    elif roll < 0.47 + HIST_P:
        if rng.random() < 0.5:
            a = rng.choice(HIST_ADJ4)
            return f"{a[GI[g]]} {b}", 'hist'
        return rng.choice(HIST_F)(b), 'hist'
    else:
        a = rng.choice(ADJ4)
        return f"{a[GI[g]]} {b}", 'adj'

